        assert_eq!(result.raw_recognized_words, 114);
        assert_eq!(result.captured_seconds, 50.0);
        assert_eq!(result.eligible_capture_seconds, 50.0);
        assert_eq!(result.recognized_words_per_captured_minute, Some(132.0));
        assert_eq!(result.typing_time_comparison_seconds, Some(75.0));
        assert_eq!(result.delivery_counts.confirmed, 1);

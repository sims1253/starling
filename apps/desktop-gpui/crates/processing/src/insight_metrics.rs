//! The production port of the frozen Insight metric oracle (#308).
//!
//! `tests/insight_metrics.py` is the executable contract
//! (`packages/contracts/insight-events/`): dedupe by `event_id`, the
//! latest recognition selection per capture, tombstones that dominate
//! stale replays, speech words separate from generated output, and the
//! time-saved proxy that is `None` — never zero — when an input is
//! unknown. This module reproduces those semantics in the native runtime,
//! typed, so a malformed log fails instead of becoming plausible-looking
//! numbers.
//!
//! The aggregate is plain JSON ([`Aggregate`]); the emitted events live in
//! [`crate::insight`]. Fixture expectations are generated by the oracle
//! into `packages/contracts/insight-events/aggregates/` and both test
//! suites assert they still match their implementation, so the Rust port
//! and the Python contract cannot drift apart.
//!
//! Not ported here: the oracle's `activity_by_day` local-calendar grouping,
//! which needs a timezone database.

